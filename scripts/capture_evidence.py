#!/usr/bin/env python3
"""
Capture browser evidence for the local API verification report.

The report is an HTML artifact generated by scripts/e2e_api_verify.py from
responses observed on the running SAM local API. This script uses Playwright
to render that artifact at desktop and mobile viewports, capture the primary
RAG workflow and error-handling sections, record browser console/request
failures, and make a small set of API calls through Playwright's request
context as a second, browser-driven check.

Usage:
    python3 scripts/capture_evidence.py
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from playwright.sync_api import Page, sync_playwright


def _record_browser_events(page: Page, console_lines: list[str], failures: list[str]) -> None:
    page.on(
        "console",
        lambda message: console_lines.append(f"{message.type}: {message.text}"),
    )
    page.on("pageerror", lambda error: failures.append(f"pageerror: {error}"))
    page.on(
        "requestfailed",
        lambda request: failures.append(
            f"requestfailed: {request.method} {request.url} "
            f"({request.failure or 'unknown failure'})"
        ),
    )


def _browser_api_checks(context: Any, base_url: str, output: Path) -> dict[str, Any]:
    """Exercise the documented endpoints through Playwright's HTTP client."""
    cases = [
        (
            "invoke",
            "/invoke",
            {"prompt": "Browser check: AWS security best practices?"},
            200,
        ),
        (
            "embed",
            "/embed",
            {"text": "Browser check embedding text", "metadata": {"source": "playwright"}},
            200,
        ),
        ("retrieve", "/retrieve", {"query": "retention policy", "top_k": 2}, 200),
        ("query", "/query", {"query": "Summarize the security controls", "top_k": 2}, 200),
        ("validation_error", "/invoke", {"prompt": "   "}, 400),
    ]
    results: list[dict[str, Any]] = []
    for name, path, payload, expected_status in cases:
        response = context.request.post(
            f"{base_url.rstrip('/')}{path}",
            data=json.dumps(payload),
            headers={"Content-Type": "application/json"},
            timeout=120_000,
        )
        try:
            body = response.json()
        except Exception:  # noqa: BLE001 - record non-JSON responses instead of failing
            body = {"_raw": response.text()[:500]}
        results.append(
            {
                "name": name,
                "path": path,
                "request": payload,
                "status": response.status,
                "expected_status": expected_status,
                "passed": response.status == expected_status,
                "response": body,
            }
        )
    checks = {
        "base_url": base_url,
        "results": results,
        "passed": sum(1 for result in results if result["passed"]),
        "total": len(results),
    }
    output.write_text(json.dumps(checks, indent=2), encoding="utf-8")
    return checks


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--html", default="docs/evidence/api-console.html")
    parser.add_argument("--output-dir", default="docs/evidence/screenshots")
    parser.add_argument("--evidence-dir", default="docs/evidence")
    parser.add_argument("--api-base-url", default="http://127.0.0.1:3000")
    args = parser.parse_args()

    html_path = Path(args.html).resolve()
    if not html_path.is_file():
        raise SystemExit(f"HTML report not found: {html_path}")

    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    evidence_dir = Path(args.evidence_dir)
    test_results = evidence_dir / "test-results"
    test_results.mkdir(parents=True, exist_ok=True)

    console_lines: list[str] = []
    failures: list[str] = []

    with sync_playwright() as playwright:
        browser = playwright.chromium.launch()

        desktop = browser.new_context(
            viewport={"width": 1440, "height": 1000},
            device_scale_factor=1,
            color_scheme="dark",
        )
        page = desktop.new_page()
        _record_browser_events(page, console_lines, failures)
        page.goto(html_path.as_uri(), wait_until="networkidle")
        page.screenshot(
            path=str(output_dir / "api-verification-desktop.png"),
            full_page=False,
        )
        page.screenshot(
            path=str(output_dir / "api-verification-full.png"),
            full_page=True,
        )

        page.locator("#query_success").scroll_into_view_if_needed()
        page.locator("#query_success").screenshot(
            path=str(output_dir / "query-workflow.png")
        )

        page.locator("#invoke_malformed_json").scroll_into_view_if_needed()
        page.locator("#invoke_malformed_json").screenshot(
            path=str(output_dir / "error-validation.png")
        )
        desktop.close()

        mobile = browser.new_context(
            viewport={"width": 390, "height": 844},
            device_scale_factor=1,
            color_scheme="dark",
            is_mobile=True,
            has_touch=True,
        )
        mobile_page = mobile.new_page()
        _record_browser_events(mobile_page, console_lines, failures)
        mobile_page.goto(html_path.as_uri(), wait_until="networkidle")
        mobile_page.screenshot(
            path=str(output_dir / "api-verification-mobile.png"),
            full_page=False,
        )
        mobile_page.screenshot(
            path=str(output_dir / "api-verification-mobile-full.png"),
            full_page=True,
        )
        mobile.close()

        api_checks: dict[str, Any] | None = None
        try:
            api_context = browser.new_context()
            api_checks = _browser_api_checks(
                api_context,
                args.api_base_url,
                test_results / "browser-api-checks.json",
            )
            api_context.close()
        except Exception as exc:  # noqa: BLE001 - evidence run should not be blocked by API downtime
            failures.append(f"browser API check failed: {exc}")

        browser.close()

    (test_results / "browser-console.log").write_text(
        "\n".join(console_lines + failures) + "\n", encoding="utf-8"
    )

    print(f"Captured screenshots in {output_dir}")
    for path in sorted(output_dir.glob("*.png")):
        print(f"  {path.name} ({path.stat().st_size} bytes)")
    print(f"Browser console entries: {len(console_lines)}")
    print(f"Browser failures: {len(failures)}")
    if api_checks is not None:
        print(f"Browser API checks: {api_checks['passed']}/{api_checks['total']} succeeded")
        if api_checks["passed"] != api_checks["total"]:
            return 1
    else:
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
